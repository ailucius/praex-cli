#!/usr/bin/env node
// Writes the Homebrew formula for one praex GitHub release.
//
//   node packaging/homebrew/generate-formula.mjs v0.1.41
//   node packaging/homebrew/generate-formula.mjs v0.1.42 --out ../homebrew-tap/Formula/praex.rb
//
// Options:
//   --out FILE       where to write (default packaging/homebrew-tap/Formula/praex.rb)
//   --repo OWNER/R   GitHub repo with the release (default ailucius/praex-cli)
//
// Hashes come from the release's SHA256SUMS and are cross-checked against the
// sha256 digests GitHub reports for each asset; any disagreement aborts.
// Platforms whose asset is not in the release are left out of the formula.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))

const ASSETS = {
  macArm: "praex-darwin-arm64.tar.gz",
  macIntel: "praex-darwin-x64.tar.gz",
  linuxIntel: "praex-linux-x64.tar.gz",
  linuxArm: "praex-linux-arm64.tar.gz",
}

function parseArgs(argv) {
  const args = { repo: "ailucius/praex-cli", out: path.resolve(here, "../homebrew-tap/Formula/praex.rb") }
  const rest = [...argv]
  while (rest.length) {
    const a = rest.shift()
    if (a === "--out") args.out = path.resolve(rest.shift())
    else if (a === "--repo") args.repo = rest.shift()
    else if (!args.tag) args.tag = a
    else throw new Error(`unknown argument: ${a}`)
  }
  return args
}

async function get(url, json) {
  const headers = json ? { accept: "application/vnd.github+json" } : {}
  if (json && process.env.GITHUB_TOKEN) headers.authorization = `Bearer ${process.env.GITHUB_TOKEN}`
  const res = await fetch(url, { headers, redirect: "follow" })
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return json ? res.json() : res.text()
}

function parseSums(text) {
  const sums = new Map()
  for (const line of text.split("\n")) {
    const m = line.trim().match(/^([0-9a-f]{64})\s+\*?(\S+)$/i)
    if (!m) continue
    const prev = sums.get(m[2])
    if (prev && prev !== m[1].toLowerCase()) throw new Error(`SHA256SUMS lists two different hashes for ${m[2]}`)
    sums.set(m[2], m[1].toLowerCase())
  }
  return sums
}

function block(indent, url, sha) {
  return [`${indent}url "${url}"`, `${indent}sha256 "${sha}"`]
}

async function main() {
  const args = parseArgs(process.argv.slice(2))
  if (!args.tag) {
    console.log("usage: node packaging/homebrew/generate-formula.mjs <tag> [--out FILE] [--repo OWNER/REPO]")
    process.exit(1)
  }
  const version = args.tag.replace(/^v/, "")
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`not a stable semver tag: ${args.tag}`)

  const base = `https://github.com/${args.repo}/releases/download/${args.tag}`
  const sums = parseSums(await get(`${base}/SHA256SUMS`, false))

  const release = await get(`https://api.github.com/repos/${args.repo}/releases/tags/${args.tag}`, true).catch((err) => {
    console.warn(`warning: could not read GitHub asset digests (${err.message}); using SHA256SUMS alone`)
    return undefined
  })
  const digests = new Map((release?.assets ?? []).map((a) => [a.name, (a.digest ?? "").replace(/^sha256:/, "")]))

  const sha = {}
  for (const [key, asset] of Object.entries(ASSETS)) {
    const s = sums.get(asset)
    if (!s) continue
    const d = digests.get(asset)
    if (release && d && d !== s) throw new Error(`${asset}: SHA256SUMS says ${s}, GitHub says ${d}`)
    sha[key] = s
    console.log(`${asset} ${s}${d ? " (matches GitHub digest)" : ""}`)
  }
  if (!sha.macArm && !sha.macIntel && !sha.linuxIntel && !sha.linuxArm) throw new Error("no usable assets in this release")

  const url = (key) => `${base}/${ASSETS[key]}`
  const lines = [
    "# typed: false",
    "# frozen_string_literal: true",
    "",
    `# Generated by packaging/homebrew/generate-formula.mjs in ${args.repo} for ${args.tag}.`,
    "# Regenerate with that script instead of editing by hand.",
    "class Praex < Formula",
    '  desc "Open source AI coding agent for the terminal"',
    '  homepage "https://praex.ai"',
    `  version "${version}"`,
    '  license "MIT"',
    "",
  ]
  if (sha.macArm || sha.macIntel) {
    lines.push("  on_macos do")
    if (sha.macArm) lines.push("    on_arm do", ...block("      ", url("macArm"), sha.macArm), "    end")
    if (sha.macIntel) lines.push("    on_intel do", ...block("      ", url("macIntel"), sha.macIntel), "    end")
    lines.push("  end", "")
  }
  if (sha.linuxIntel || sha.linuxArm) {
    lines.push("  on_linux do")
    if (sha.linuxArm) lines.push("    on_arm do", ...block("      ", url("linuxArm"), sha.linuxArm), "    end")
    if (sha.linuxIntel) lines.push("    on_intel do", ...block("      ", url("linuxIntel"), sha.linuxIntel), "    end")
    lines.push("  end", "")
  }
  lines.push(
    "  def install",
    '    libexec.install "praex"',
    "    # Homebrew owns updates (brew upgrade praex), so the built in updater stays",
    "    # off unless the user sets PRAEX_DISABLE_AUTOUPDATE=0 themselves.",
    '    (bin/"praex").write_env_script libexec/"praex", PRAEX_DISABLE_AUTOUPDATE: "${PRAEX_DISABLE_AUTOUPDATE:-1}"',
    "  end",
    "",
    "  test do",
    '    assert_equal version.to_s, shell_output("#{bin}/praex --version").strip',
    "  end",
    "end",
    "",
  )

  fs.mkdirSync(path.dirname(args.out), { recursive: true })
  fs.writeFileSync(args.out, lines.join("\n"))
  console.log(`wrote ${args.out}`)
}

main().catch((err) => {
  console.error(`error: ${err.message}`)
  process.exit(1)
})
